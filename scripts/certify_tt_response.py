"""Print the finite Gaussian TT response-domain certificate.

This is a read-only certificate command.  It evaluates the explicit-``R``
endpoint ``c(R)`` and the three-position platform, and prints the result as
JSON.  It does not write the production parameter store.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

_ROOT = Path(__file__).resolve().parent.parent
if str(_ROOT) not in sys.path:
    sys.path.insert(0, str(_ROOT))

from cg_frg.frg.tt_response_domain import certificate  # noqa: E402


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, help="optional JSON output path")
    args = parser.parse_args(argv)

    result = certificate()
    text = json.dumps(result, indent=2, sort_keys=True)
    print(text)
    if args.output is not None:
        args.output.write_text(text + "\n", encoding="utf-8")
    return 0 if result["unique_integer_level"] == 5 else 1


if __name__ == "__main__":
    raise SystemExit(main())
